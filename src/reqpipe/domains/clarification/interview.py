"""1.1 · Сократическое интервью."""

from reqpipe.core import Consumes, Context, Element, Instructions
from reqpipe.domains.clarification.contracts import IdeaBrief
from reqpipe.domains.intake.contracts import RawIdea


def example(ctx: Context) -> dict:
    idea = ctx.input("idea").get("text", "")
    return {
        "goal": f"Проверить и развить замысел: {idea[:120]}",
        "problem": "Пользователи тратят слишком много времени на рутинную задачу и ошибаются",
        "target_audience": ["Частные пользователи", "Малые команды"],
        "context": "Существующие решения сложны и не закрывают ключевые сценарии",
        "constraints": ["Бюджет MVP ограничен", "Хранение персональных данных в РФ"],
        "success_criteria": ["Время выполнения задачи сокращается вдвое"],
        "assumptions": [
            {"id": "ASM-001", "statement": "Пользователи готовы платить за экономию времени",
             "how_to_verify": "Анализ отзывов и тарифов конкурентов"},
        ],
        "open_questions": [],
        "qa_log": [{"question": "Кто страдает от проблемы?", "answer": "Частные пользователи и малые команды",
                    "is_assumption": ctx.autonomous}],
    }


ELEMENT = Element(
    id="clarify", num="1.1", title="Сократическое интервью", actor="Агент-интервьюер", kind="agent",
    checkpoint=True,
    instructions=Instructions(
        purpose=(
            "Превратить расплывчатый замысел в осмысленный бриф. Агент ведёт диалог с автором, "
            "пока не будут закрыты ключевые вопросы, и явно отделяет факты от допущений."
        ),
        methods=(
            "Вопросы по схеме 5W2H: что, зачем, кто, где, когда, как, сколько",
            "«Пять почему» — поиск корневой проблемы за желаемым решением",
            "Выявление и маркировка скрытых допущений",
            "Адаптивная глубина: агент сам решает, когда информации достаточно",
        ),
        prompt=(
            "Ты — опытный бизнес-аналитик. Не предлагай решений. Задавай по одному вопросу за раз, "
            "пока не поймёшь проблему, аудиторию, контекст и критерии успеха."
        ),
        done="Все разделы брифа заполнены; каждое допущение помечено и имеет способ проверки.",
        hitl="Автор идеи отвечает на вопросы и подтверждает итоговый бриф.",
        auto_note=(
            "После постановки задачи автор идеи не участвует: агент сам отвечает на свои вопросы, выбирая "
            "наиболее вероятный вариант, и помечает каждый ответ как допущение. Все допущения затем "
            "проверяются данными исследования и фильтром G0."
        ),
        auto_prompt=(
            "Ты — опытный бизнес-аналитик. Задай себе ключевые вопросы о проблеме, аудитории, контексте и "
            "критериях успеха. Для каждого выбери наиболее вероятный ответ по идее и данным рынка и пометь "
            "его как допущение."
        ),
    ),
    consumes=(Consumes("idea", RawIdea),),
    output=IdeaBrief,
    example=example,
)
